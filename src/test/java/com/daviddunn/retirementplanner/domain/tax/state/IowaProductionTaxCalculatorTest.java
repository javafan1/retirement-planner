class IowaProductionTaxCalculatorTest {
    private static final BigDecimal ZERO = BigDecimal.ZERO;

    static Stream<JsonNode> worksheets() throws Exception {
        try (var input = IowaProductionTaxCalculatorTest.class.getResourceAsStream("/tax/state/phase6d5a-admission-worksheets.json")) {
            var rows = new ArrayList<JsonNode>();
            new ObjectMapper().readTree(input).forEach(row -> { if (row.path("state").asText().equals("IA")) rows.add(row); });
            assertEquals(26, rows.size());
            return rows.stream();
        }
    }

    @ParameterizedTest(name = "{index}: {0}")
    @MethodSource("worksheets")
    void preservesAllAuditWorksheetOutcomesAtTheirHonestBoundary(JsonNode row) throws Exception {
        String id = row.path("id").asText();
        // These rows stipulate final legal bases/qualified Roth proof, not facts generated by the planner.
        if (id.equals("IA13") || id.equals("IA26")) {
            var rules = new IowaTaxRulesRepository().load();
            var taxable = new BigDecimal(row.path("taxableBeforeBand").asText());
            var outcome = new IowaLowIncomeReliefCalculator().calculate(new IowaLowIncomeReliefCalculator.Inputs(
                    FilingStatus.SINGLE, taxable.multiply(rules.rate()), id.equals("IA13") ? ZERO : new BigDecimal("120000"),
                    id.equals("IA26"), new BigDecimal(row.path("credit").asText())), rules);
            assertEquals(0, new BigDecimal(row.path("expectedTax").asText()).compareTo(outcome.finalRawTax().setScale(2, RoundingMode.HALF_UP)));
            return;
        }
        LocalDate birth = LocalDate.of(1966, 1, 1);
        BigDecimal pension = ZERO, ss = ZERO, withdrawal = ZERO, conversion = ZERO, investment = ZERO;
        var sources = new ArrayList<IncomeSourceAttribution>();
        boolean couple = id.equals("IA18");
        switch (id) {
            case "IA01" -> ss = new BigDecimal("30000");
            case "IA02", "IA03", "IA04" -> {
                investment = new BigDecimal("60000");
                var kind = id.equals("IA02") ? IncomeSourceAttribution.Kind.INTEREST
                        : id.equals("IA03") ? IncomeSourceAttribution.Kind.DIVIDEND : IncomeSourceAttribution.Kind.CAPITAL_GAIN;
                sources.add(IncomeSourceAttribution.aggregate(kind, IncomeSourceAttribution.Purpose.INCOME, id, investment, Optional.of(investment)).inYear(2026));
            }
            case "IA09", "IA10", "IA17" -> {
                pension = new BigDecimal(id.equals("IA17") ? "40000" : "30000");
                if (id.equals("IA09")) birth = LocalDate.of(1961, 1, 1);
                if (id.equals("IA10")) birth = LocalDate.of(1976, 1, 1);
                if (id.equals("IA17")) investment = new BigDecimal("60000");
                var owner = id.equals("IA10") ? AccountOwnership.SPOUSE : AccountOwnership.PRIMARY;
                sources.add(IncomeSourceAttribution.pension(new com.daviddunn.retirementplanner.domain.income.Pension(
                        id, owner, LocalDate.of(2020, 1, 1), null, new BigDecimal("2500"), ZERO),
                        AccountOwnership.PRIMARY, pension, 2026));
            }
            case "IA25" -> { birth = LocalDate.of(1961, 1, 1); investment = new BigDecimal("20000"); }
            default -> {
                BigDecimal amount = new BigDecimal("40000");
                if (id.equals("IA06")) amount = new BigDecimal("60000");
                if (id.equals("IA14")) { amount = new BigDecimal("20000"); birth = LocalDate.of(1972, 1, 1); }
                if (id.equals("IA15")) birth = LocalDate.of(1976, 1, 1);
                if (id.equals("IA20")) amount = new BigDecimal("500000");
                Account source = new TraditionalIRA(id, AccountOwnership.PRIMARY, amount);
                var kind = IncomeSourceAttribution.Kind.ORDINARY_RETIREMENT_WITHDRAWAL;
                var purpose = IncomeSourceAttribution.Purpose.CASH_FLOW;
                if (Set.of("IA05", "IA11").contains(id)) birth = LocalDate.of(1971, 6, 1);
                if (Set.of("IA06", "IA12", "IA22").contains(id)) birth = LocalDate.of(1972, 1, 1);
                if (id.equals("IA21")) birth = LocalDate.of(1971, 12, 31);
                if (id.equals("IA07")) { birth = LocalDate.of(1951, 1, 1); kind = IncomeSourceAttribution.Kind.RMD; }
                if (Set.of("IA08", "IA19", "IA23").contains(id)) source = new Traditional401K(id, AccountOwnership.PRIMARY, amount);
                if (id.equals("IA08") || id.equals("IA19")) {
                    var event = LocalDate.of(id.equals("IA19") ? 2030 : 2020, 1, 1);
                    source.setRetirementParticipantFacts(new RetirementParticipantFacts(RetirementParticipantFacts.SeparationStatus.SEPARATED,
                            event, RetirementParticipantFacts.RetirementConditionsStatus.MET, event));
                }
                if (id.equals("IA14")) source = new RothIRA(id, AccountOwnership.PRIMARY, amount);
                if (id.equals("IA15")) source = new InheritedTraditionalIRA(id, AccountOwnership.PRIMARY, amount,
                        new InheritedAccountInformation(LocalDate.of(1930, 1, 1), LocalDate.of(2020, 1, 1), BeneficiaryRelationship.SPOUSE));
                if (Set.of("IA11", "IA12", "IA23", "IA24").contains(id)) {
                    kind = IncomeSourceAttribution.Kind.ROTH_CONVERSION;
                    purpose = IncomeSourceAttribution.Purpose.CONVERSION;
                    conversion = amount;
                    sources.add(new IncomeSourceAttribution(kind, purpose, Optional.of(AccountOwnership.PRIMARY),
                            Optional.of(IncomeSourceAttribution.AccountReference.capture(source)),
                            Optional.of(IncomeSourceAttribution.AccountReference.capture(new RothIRA("Destination", AccountOwnership.PRIMARY, ZERO))),
                            id, amount, id.equals("IA24") ? Optional.empty() : Optional.of(amount), OptionalInt.of(2026), Optional.empty()));
                } else {
                    if (id.equals("IA20")) { amount = new BigDecimal("500000"); investment = new BigDecimal("100000"); }
                    if (id.equals("IA16")) investment = new BigDecimal("60000");
                    withdrawal = id.equals("IA14") ? ZERO : amount;
                    sources.add(IncomeSourceAttribution.withdrawal(source, amount, kind, purpose).inYear(2026));
                }
                if (couple) {
                    birth = LocalDate.of(1971, 1, 1);
                    sources.add(IncomeSourceAttribution.withdrawal(new TraditionalIRA("Spouse", AccountOwnership.SPOUSE, amount), amount, kind, purpose).inYear(2026));
                    withdrawal = amount.multiply(BigDecimal.TWO);
                }
            }
        }
        var request = request(birth, couple ? LocalDate.of(1972, 1, 1) : null,
                new TaxIncome(pension, ss, withdrawal, conversion, investment, sources), new BigDecimal("20000"));
        var result = new IowaProductionTaxCalculator().calculate(request);
        if (row.path("outcome").asText().equals("EXPECTED_UNSUPPORTED")) {
            assertEquals(StateTaxCalculationStatus.UNSUPPORTED, result.calculationStatus(), id);
            assertTrue(result.estimatedIncomeTax().isEmpty(), id);
            assertTrue(result.unavailableReasons().contains(StateTaxUnavailableReason.valueOf(row.path("reason").asText())), id);
        } else {
            assertEquals(0, new BigDecimal(row.path("expectedTax").asText()).compareTo(result.incomeTax()), id);
            assertTrue(result.limitations().getFirst().contains("not assumed to be zero"));
        }
    }

    static StateTaxCalculationRequest request(LocalDate primary, LocalDate spouse, TaxIncome income, BigDecimal deduction) throws Exception {
        var original = new GovernmentRulesRepository().load("/rules/government-rules-2026.json");
        var status = spouse == null ? FilingStatus.SINGLE : FilingStatus.MARRIED_FILING_JOINTLY;
        // Stipulated worksheet deduction; published rule resources remain untouched.
        var federalRules = original.getFederalTaxRules().stream().map(rule -> rule.getFilingStatus() == status
                ? new FederalTaxRules(status, deduction, rule.getTaxBrackets()) : rule).toList();
        var rules = new GovernmentRules(original.getRulesVersion(), original.getTaxYear(), original.getEffectiveDate(),
                federalRules, original.getMichiganTaxRules(), original.getIrmaaRules(), original.getSocialSecurityTaxRules(), original.getRmdRules());
        var births = new EnumMap<AccountOwnership, LocalDate>(AccountOwnership.class);
        births.put(AccountOwnership.PRIMARY, primary);
        if (spouse != null) births.put(AccountOwnership.SPOUSE, spouse);
        return new StateTaxCalculationRequest(2026, status,
                new TaxHouseholdContext(LocalDate.of(2026, 1, 1), births, births.keySet(), births.keySet(), Optional.empty()),
                income, new FederalTaxCalculator().calculate(income, status, rules), rules, StateTaxAssumptions.simplified(StateTaxJurisdiction.IA));
    }

    @ParameterizedTest
    @ValueSource(strings = {"1971-12-31", "1972-01-01"})
    void retirementAgeBoundaryUsesDecember31(String dob) throws Exception {
        var amount = new BigDecimal("40000");
        var source = IncomeSourceAttribution.withdrawal(new TraditionalIRA("IRA", AccountOwnership.PRIMARY, amount), amount,
                IncomeSourceAttribution.Kind.ORDINARY_RETIREMENT_WITHDRAWAL, IncomeSourceAttribution.Purpose.CASH_FLOW).inYear(2026);
        var result = new IowaProductionTaxCalculator().calculate(request(LocalDate.parse(dob), null,
                new TaxIncome(ZERO, ZERO, amount, ZERO, ZERO, List.of(source)), new BigDecimal("16100")));
        assertEquals(dob.equals("1971-12-31"), result.estimatedIncomeTax().isPresent());
    }

    @Test
    void observerMismatchIsTypedRefusalNotFederalRepair() throws Exception {
        var request = request(LocalDate.of(1966, 1, 1), null, new TaxIncome(ZERO, ZERO, ZERO, ZERO, new BigDecimal("60000")), new BigDecimal("16100"));
        var inconsistent = new FederalTaxCalculation(request.federal().getAdjustedGrossIncome(), ZERO, new BigDecimal("16100"), ZERO, ZERO);
        var result = new IowaProductionTaxCalculator().calculate(new StateTaxCalculationRequest(2026, request.filingStatus(), request.household(),
                request.income(), inconsistent, request.projectedRules(), request.assumptions()));
        assertEquals(List.of(StateTaxUnavailableReason.UNSUPPORTED_MODEL_RULE), result.unavailableReasons());
        assertEquals(ZERO, inconsistent.getTaxableIncome());
    }

    @Test
    void unsupportedPensionPrecedesLowIncomeZeroShortcut() throws Exception {
        var result = new IowaProductionTaxCalculator().calculate(request(LocalDate.of(1961, 1, 1), null,
                new TaxIncome(BigDecimal.ONE, ZERO, ZERO, ZERO, ZERO), new BigDecimal("16100")));
        assertTrue(result.estimatedIncomeTax().isEmpty());
        assertEquals(List.of(StateTaxUnavailableReason.MISSING_RETIREMENT_QUALIFICATION), result.unavailableReasons());
    }

    @Test
    void openingRmdSignedBaseAndTaxableSocialSecurityAreExcludedOnce() throws Exception {
        var amount = new BigDecimal("100000");
        var source = IncomeSourceAttribution.withdrawal(new TraditionalIRA("IRA", AccountOwnership.PRIMARY, amount), amount,
                IncomeSourceAttribution.Kind.OPENING_RMD, IncomeSourceAttribution.Purpose.INCOME).inYear(2026);
        var request = request(LocalDate.of(1951, 1, 1), null, new TaxIncome(ZERO, new BigDecimal("40000"), amount, ZERO, ZERO, List.of(source)), new BigDecimal("16100"));
        var base = new IowaTaxBaseBridge().reconcile(request, request.federal().getModeledBaseBreakdown(), new IowaTaxRulesRepository().load()).amounts().orElseThrow();
        assertEquals(0, new BigDecimal("-16100").compareTo(base.signedIowaBase()));
        assertEquals(0, base.reliefIncome().signum());
        assertEquals(request.federal().getTaxableSocialSecurity(), base.taxableSocialSecurityExcluded());
        assertEquals(0, new IowaProductionTaxCalculator().calculate(request).incomeTax().signum());
    }
}
