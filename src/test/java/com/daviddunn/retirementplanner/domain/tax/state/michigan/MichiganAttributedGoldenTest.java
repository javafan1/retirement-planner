    void pensionConversionAndInterestShareOnlyProvenIraCapacity(String pension, String ira,
            String conversion, String interest, String deduction, String taxable, String tax) throws Exception {
        var household = new Household(new Person("Primary", "Fixture", LocalDate.of(1966, 1, 1)));
        List<IncomeSourceAttribution> sources = new ArrayList<>();
        add(sources, AccountOwnership.PRIMARY, ira, false);
        add(sources, AccountOwnership.PRIMARY, conversion, true);
        if (money(pension).signum() > 0) {
            sources.add(IncomeSourceAttribution.aggregate(IncomeSourceAttribution.Kind.PENSION,
                    IncomeSourceAttribution.Purpose.INCOME, "Pension qualification unavailable", money(pension), Optional.of(money(pension))));
        }
        var result = new MichiganTaxCalculator().calculate(new TaxIncome(money(pension), BigDecimal.ZERO,
                money(ira), money(conversion), money(interest), sources), FilingStatus.SINGLE,
                new GovernmentRulesRepository().load("/rules/government-rules-2026.json").getMichiganTaxRules(),
                MichiganTaxContext.capture(household, DATE, null));
        amount(deduction, result.retirementDeduction());
        amount(taxable, result.taxableIncome());
        amount(tax, result.incomeTax().setScale(2, RoundingMode.HALF_UP));
    }

    static void amount(String expected, BigDecimal actual) {
        assertEquals(0, money(expected).compareTo(actual), expected + " versus " + actual);
    }
