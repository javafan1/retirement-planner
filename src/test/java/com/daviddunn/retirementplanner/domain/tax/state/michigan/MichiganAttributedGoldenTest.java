    void independentSourceAwareWorksheets(String id, FilingStatus status, String primaryAge, String spouseAge,
            String primaryIra, String spouseIra, String primaryConversion, String spouseConversion,
            String interest, String ss, String subtraction, String taxable, String tax) throws Exception {
        var household = new Household(new Person("Primary", "Fixture", birth(primaryAge)),
                status == FilingStatus.SINGLE ? null : new Person("Spouse", "Fixture", birth(spouseAge)));
        List<IncomeSourceAttribution> sources = new ArrayList<>();
        add(sources, AccountOwnership.PRIMARY, primaryIra, false);
        add(sources, AccountOwnership.SPOUSE, spouseIra, false);
        add(sources, AccountOwnership.PRIMARY, primaryConversion, true);
        add(sources, AccountOwnership.SPOUSE, spouseConversion, true);
        var income = new TaxIncome(BigDecimal.ZERO, money(ss), money(primaryIra).add(money(spouseIra)),
                money(primaryConversion).add(money(spouseConversion)), money(interest), sources);
        var result = new MichiganTaxCalculator().calculate(income, status,
                new GovernmentRulesRepository().load("/rules/government-rules-2026.json").getMichiganTaxRules(),
                MichiganTaxContext.capture(household, DATE, null));
        amount(subtraction, result.retirementDeduction());
        amount(taxable, result.taxableIncome());
        amount(tax, result.incomeTax().setScale(2, RoundingMode.HALF_UP));
        amount(status == FilingStatus.SINGLE ? "5900" : "11800", result.personalExemption());
    }

    private static LocalDate birth(String age) {
        return switch (age) {
            case "59.4" -> LocalDate.of(1966, 8, 1);
            case "59.5" -> LocalDate.of(1966, 7, 1);
            default -> DATE.minusYears(Long.parseLong(age));
        };
    }

    static void add(List<IncomeSourceAttribution> sources, AccountOwnership owner, String text, boolean conversion) {
        if (money(text).signum() > 0) {
            var account = new TraditionalIRA(owner + " IRA", owner, money(text));
            var source = IncomeSourceAttribution.withdrawal(account, money(text), conversion
                    ? IncomeSourceAttribution.Kind.ROTH_CONVERSION : IncomeSourceAttribution.Kind.ORDINARY_RETIREMENT_WITHDRAWAL,
                    conversion ? IncomeSourceAttribution.Purpose.CONVERSION : IncomeSourceAttribution.Purpose.CASH_FLOW);
            sources.add(source.inYear(2026));
        }
    }

    @ParameterizedTest
    @CsvSource({"PENSION,100000,0,94100,3999.25", "EMPLOYER,100000,0,94100,3999.25",
            "PENSION,30000,50000,24100,1024.25", "EMPLOYER,50000,50000,44100,1874.25"})
    void unavailableQualificationsReceiveNoUnprovenSubtraction(String kind, String unknown,
            String knownIra, String taxable, String tax) throws Exception {
        var person = new Person("Primary", "Fixture", LocalDate.of(1966, 1, 1));
        var household = new Household(person);
        List<IncomeSourceAttribution> sources = new ArrayList<>();
        add(sources, AccountOwnership.PRIMARY, knownIra, false);
        BigDecimal pension = kind.equals("PENSION") ? money(unknown) : BigDecimal.ZERO;
        BigDecimal withdrawals = kind.equals("PENSION") ? money(knownIra) : money(unknown).add(money(knownIra));
        if (kind.equals("PENSION")) {
            var source = new com.daviddunn.retirementplanner.domain.income.Pension("Unclassified pension",
                    AccountOwnership.PRIMARY, DATE, null, money(unknown).divide(new BigDecimal("12"), 10, RoundingMode.HALF_UP), BigDecimal.ZERO);
            sources.add(IncomeSourceAttribution.pension(source, AccountOwnership.PRIMARY, money(unknown), 2026));
        } else {
            var account = new Traditional401K("Unknown contribution composition", AccountOwnership.PRIMARY, money(unknown));
            sources.add(IncomeSourceAttribution.withdrawal(account, money(unknown), IncomeSourceAttribution.Kind.RMD,
                    IncomeSourceAttribution.Purpose.CASH_FLOW));
        }
        var result = new MichiganTaxCalculator().calculate(new TaxIncome(pension, BigDecimal.ZERO, withdrawals,
                BigDecimal.ZERO, BigDecimal.ZERO, sources), FilingStatus.SINGLE,
                new GovernmentRulesRepository().load("/rules/government-rules-2026.json").getMichiganTaxRules(),
                MichiganTaxContext.capture(household, DATE, null));
        amount(taxable, result.taxableIncome());
        amount(tax, result.incomeTax().setScale(2, RoundingMode.HALF_UP));
        assertTrue(result.usedConservativeEligibility());
    }

    @Test
    void earlierOpeningReceiptDoesNotBorrowEligibilityFromProjectionStart() throws Exception {
        var household = new Household(new Person("Primary", "Fixture", LocalDate.of(1966, 9, 1)));
        var account = new TraditionalIRA("IRA", AccountOwnership.PRIMARY, money("20000"));
        var source = IncomeSourceAttribution.withdrawal(account, money("20000"),
                IncomeSourceAttribution.Kind.OPENING_RMD, IncomeSourceAttribution.Purpose.INCOME);
        // No pre-projection receipt date is known; Jan1 is the conservative lower boundary.
        var result = new MichiganTaxCalculator().calculate(new TaxIncome(BigDecimal.ZERO, BigDecimal.ZERO,
                money("20000"), BigDecimal.ZERO, BigDecimal.ZERO, List.of(source)), FilingStatus.SINGLE,
                new GovernmentRulesRepository().load("/rules/government-rules-2026.json").getMichiganTaxRules(),
                MichiganTaxContext.capture(household, LocalDate.of(2026, 7, 1), null));
        amount("0", result.retirementDeduction());
    }

